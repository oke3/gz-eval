import type { EvalReport, ABComparison, EvalResult } from '../core/types.js'

/** Generate a self-contained HTML report from an EvalReport */
export function generateReportHtml(report: EvalReport): string {
  const { summary, results, config } = report

  const metricNames = Object.keys(summary.metricAverages)
  const metricBars = metricNames
    .map((name) => {
      const avg = summary.metricAverages[name]
      const pct = Math.round(avg * 100)
      return `
      <div class="metric-bar">
        <div class="metric-label">${escapeHtml(name)}</div>
        <div class="metric-track">
          <div class="metric-fill" style="width: ${pct}%"></div>
        </div>
        <div class="metric-value">${pct}%</div>
      </div>`
    })
    .join('')

  const resultRows = results
    .map((r) => {
      const score = r.metrics.length > 0
        ? r.metrics.reduce((s, m) => s + m.score, 0) / r.metrics.length
        : 0
      const statusClass = r.passed ? 'pass' : r.error ? 'error' : 'fail'
      const statusLabel = r.passed ? 'PASS' : r.error ? 'ERROR' : 'FAIL'
      const scorePct = Math.round(score * 100)

      return `
      <tr class="result-row ${statusClass}">
        <td class="case-id">${escapeHtml(r.caseId)}</td>
        <td class="query-cell">${escapeHtml(truncate(r.query, 60))}</td>
        <td class="score-cell">
          <span class="score-badge ${statusClass}">${scorePct}%</span>
        </td>
        <td class="status-cell"><span class="status-badge ${statusClass}">${statusLabel}</span></td>
        <td class="latency-cell">${r.latencyMs}ms</td>
      </tr>`
    })
    .join('')

  return `<!DOCTYPE html>
<html lang="en">
<head>
  <meta charset="UTF-8">
  <meta name="viewport" content="width=device-width, initial-scale=1.0">
  <title>${escapeHtml(config.name)} — Eval Report</title>
  <style>${getStyles()}</style>
</head>
<body>
  <header>
    <h1>${escapeHtml(config.name)}</h1>
    <p class="subtitle">Evaluation Report &middot; ${new Date(report.timestamp).toLocaleString()}</p>
    <p class="description">${escapeHtml(config.description || 'No description')}</p>
  </header>

  <section class="summary-cards">
    <div class="card">
      <div class="card-value">${summary.totalCases}</div>
      <div class="card-label">Total Cases</div>
    </div>
    <div class="card">
      <div class="card-value">${Math.round(summary.passRate * 100)}%</div>
      <div class="card-label">Pass Rate</div>
    </div>
    <div class="card">
      <div class="card-value">${Math.round(summary.meanScore * 100)}%</div>
      <div class="card-label">Mean Score</div>
    </div>
    <div class="card">
      <div class="card-value">${summary.p50LatencyMs}ms</div>
      <div class="card-label">P50 Latency</div>
    </div>
    <div class="card">
      <div class="card-value">${summary.p95LatencyMs}ms</div>
      <div class="card-label">P95 Latency</div>
    </div>
    <div class="card">
      <div class="card-value">${summary.p99LatencyMs}ms</div>
      <div class="card-label">P99 Latency</div>
    </div>
  </section>

  <section class="metrics-section">
    <h2>Metric Breakdown</h2>
    <div class="metrics-grid">${metricBars}</div>
  </section>

  <section class="results-section">
    <h2>Per-Case Results</h2>
    <div class="table-wrapper">
      <table>
        <thead>
          <tr>
            <th>Case ID</th>
            <th>Query</th>
            <th>Score</th>
            <th>Status</th>
            <th>Latency</th>
          </tr>
        </thead>
        <tbody>${resultRows}</tbody>
      </table>
    </div>
  </section>

  <footer>
    <p>Generated by <strong>gz-eval</strong> &middot; Report ID: ${report.id.slice(0, 8)}</p>
  </footer>
</body>
</html>`
}

/** Generate HTML for A/B comparison view */
export function generateComparisonHtml(comparison: ABComparison): string {
  const { reportA, reportB, differences, winner, nameA, nameB } = comparison

  const diffRows = differences
    .map((d) => {
      const sigClass = d.significant ? 'significant' : 'not-significant'
      const arrow = d.delta > 0 ? '▲' : d.delta < 0 ? '▼' : '—'
      return `
      <tr class="${sigClass}">
        <td>${escapeHtml(d.metric)}</td>
        <td>${Math.round(d.scoreA * 100)}%</td>
        <td>${Math.round(d.scoreB * 100)}%</td>
        <td class="delta ${d.delta > 0 ? 'positive' : d.delta < 0 ? 'negative' : ''}">
          ${arrow} ${Math.abs(d.delta * 100).toFixed(1)}%
        </td>
        <td>${d.significant ? 'Yes' : 'No'}</td>
      </tr>`
    })
    .join('')

  const winnerLabel = winner === 'tie' ? 'No clear winner' : `Winner: ${winner === 'A' ? nameA : nameB}`

  return `<!DOCTYPE html>
<html lang="en">
<head>
  <meta charset="UTF-8">
  <meta name="viewport" content="width=device-width, initial-scale=1.0">
  <title>A/B Comparison — ${escapeHtml(nameA)} vs ${escapeHtml(nameB)}</title>
  <style>${getStyles()}</style>
</head>
<body>
  <header>
    <h1>A/B Comparison</h1>
    <p class="subtitle">${escapeHtml(nameA)} vs ${escapeHtml(nameB)}</p>
    <div class="winner-banner">${winnerLabel}</div>
  </header>

  <section class="comparison-overview">
    <div class="side-by-side">
      <div class="side-card">
        <h3>${escapeHtml(nameA)}</h3>
        <div class="stat">Mean Score: ${Math.round(reportA.summary.meanScore * 100)}%</div>
        <div class="stat">Pass Rate: ${Math.round(reportA.summary.passRate * 100)}%</div>
        <div class="stat">Cases: ${reportA.summary.totalCases}</div>
      </div>
      <div class="vs">VS</div>
      <div class="side-card">
        <h3>${escapeHtml(nameB)}</h3>
        <div class="stat">Mean Score: ${Math.round(reportB.summary.meanScore * 100)}%</div>
        <div class="stat">Pass Rate: ${Math.round(reportB.summary.passRate * 100)}%</div>
        <div class="stat">Cases: ${reportB.summary.totalCases}</div>
      </div>
    </div>
  </section>

  <section class="differences-section">
    <h2>Metric Differences</h2>
    <div class="table-wrapper">
      <table>
        <thead>
          <tr>
            <th>Metric</th>
            <th>${escapeHtml(nameA)}</th>
            <th>${escapeHtml(nameB)}</th>
            <th>Delta</th>
            <th>Significant</th>
          </tr>
        </thead>
        <tbody>${diffRows}</tbody>
      </table>
    </div>
  </section>

  <footer>
    <p>Generated by <strong>gz-eval</strong> &middot; A/B Comparison</p>
  </footer>
</body>
</html>`
}

/** Get report HTML as a Buffer */
export function getReportBuffer(report: EvalReport): Buffer {
  return Buffer.from(generateReportHtml(report), 'utf-8')
}

/** Get comparison HTML as a Buffer */
export function getComparisonBuffer(comparison: ABComparison): Buffer {
  return Buffer.from(generateComparisonHtml(comparison), 'utf-8')
}

// ── Helpers ──

function escapeHtml(text: string): string {
  return text
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
}

function truncate(text: string, maxLen: number): string {
  return text.length > maxLen ? text.slice(0, maxLen - 3) + '...' : text
}

